const mongoose = require("mongoose");
const fs = require("fs");
const path = require("path");

function getMongoUri() {
  const envPath = path.resolve(process.cwd(), ".env.local");
  const lines = fs.readFileSync(envPath, "utf-8").split("\n");
  for (const line of lines) {
    const trimmed = line.trim();
    if (trimmed.startsWith("MONGODB_URI=")) {
      return trimmed.slice("MONGODB_URI=".length).replace(/["']/g, "").trim();
    }
  }
}

async function main() {
  await mongoose.connect(getMongoUri());
  const db = mongoose.connection.db;
  const productsColl = db.collection("products");
  const inventoryColl = db.collection("inventories");

  const allProductIds = new Set((await productsColl.find({}, { projection: { _id: 1 } }).toArray()).map(p => p._id.toString()));
  const allInventories = await inventoryColl.find({}).toArray();

  console.log("=== Orphan Inventory Entries (productId not in products collection) ===");
  for (const inv of allInventories) {
    const pid = inv.productId ? inv.productId.toString() : "null";
    if (!allProductIds.has(pid)) {
      console.log(`Inventory ID: ${inv._id}, productId: ${pid}, quantity: ${inv.quantity}, rackId: ${inv.rackId}, warehouseId: ${inv.warehouseId}, createdAt: ${inv.createdAt}`);
    }
  }

  console.log("\n=== Multi-location count calculation ===");
  // Calculate total extra entries from multi-location
  const group = await inventoryColl.aggregate([
    { $match: { productId: { $in: Array.from(allProductIds).map(id => new mongoose.Types.ObjectId(id)) } } },
    { $group: { _id: "$productId", count: { $sum: 1 } } },
  ]).toArray();

  let singleLocation = 0;
  let multiLocationCount = 0;
  let extraEntries = 0;
  for (const g of group) {
    if (g.count === 1) singleLocation++;
    else {
      multiLocationCount++;
      extraEntries += (g.count - 1);
    }
  }
  console.log(`Products in catalog with 1 rack/location: ${singleLocation}`);
  console.log(`Products in catalog with >1 racks/locations: ${multiLocationCount}`);
  console.log(`Total extra location rows generated by multi-location: ${extraEntries}`);
  console.log(`Total catalog inventory rows = ${singleLocation} + ${multiLocationCount} + ${extraEntries} = ${singleLocation + multiLocationCount + extraEntries}`);

  await mongoose.disconnect();
}

main().catch(console.error);

